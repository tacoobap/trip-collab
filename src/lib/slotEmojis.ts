export type SlotEmoji = {
  emoji: string
  label: string
  /** Extra search terms — the label alone often isn't what people type. */
  keywords?: string[]
}

export type SlotEmojiGroup = {
  name: string
  emojis: SlotEmoji[]
}

/** Compact entry: [emoji, label, ...keywords] — keeps this file readable. */
type Row = [string, string, ...string[]]

function group(name: string, rows: Row[]): SlotEmojiGroup {
  return {
    name,
    emojis: rows.map(([emoji, label, ...keywords]) => ({
      emoji,
      label,
      keywords: keywords.length ? keywords : undefined,
    })),
  }
}

