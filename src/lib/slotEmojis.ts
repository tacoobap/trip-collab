/** Does this entry match a lowercased search term? */
export function matchesEmoji(entry: SlotEmoji, groupName: string, q: string): boolean {
  if (entry.label.toLowerCase().includes(q)) return true
  if (groupName.toLowerCase().includes(q)) return true
  return (entry.keywords ?? []).some((k) => k.includes(q))
}
